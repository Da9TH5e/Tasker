$ErrorActionPreference = 'Stop'
$python = Join-Path $PSScriptRoot '.venv/Scripts/python.exe'
if (-not (Test-Path -LiteralPath $python)) {
    throw 'Set up the Python virtual environment using the README first.'
}
$email = (Read-Host 'Gmail address').Trim()
if ($email -notmatch '^[^\s@]+@[^\s@]+$') {
    throw 'Enter the full email address for your Gmail account.'
}
$secret = Read-Host 'Google app password' -AsSecureString
$previousEmail = [Environment]::GetEnvironmentVariable('TASKER_GMAIL_EMAIL', 'Process')
$previousPassword = [Environment]::GetEnvironmentVariable('TASKER_GMAIL_APP_PASSWORD', 'Process')
try {
    $env:TASKER_GMAIL_EMAIL = $email
    $env:TASKER_GMAIL_APP_PASSWORD = [System.Net.NetworkCredential]::new('', $secret).Password -replace '\s', ''
    if (-not $env:TASKER_GMAIL_APP_PASSWORD) { throw 'Enter the app password generated by Google.' }
    & $python (Join-Path $PSScriptRoot 'backend/app.py')
} finally {
    [Environment]::SetEnvironmentVariable('TASKER_GMAIL_EMAIL', $previousEmail, 'Process')
    [Environment]::SetEnvironmentVariable('TASKER_GMAIL_APP_PASSWORD', $previousPassword, 'Process')
}
